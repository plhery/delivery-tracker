/*
 * Generates packages/carriers/generated/registry.ts: the static list of
 * adapter factories and the carrier → adapter mapping, derived from the
 * folders so nothing has to be registered by hand. Also generates
 * packages/carriers/generated/recognition.ts, the popularity rank of the
 * carriers whose adapter can recognize a number, which the public catalog
 * does not carry.
 *
 * Resolution, per carrier:
 *   link-only mode                         -> null
 *   tracking.adapter is 'universal'        -> 'universal'
 *   the folder has adapter.ts              -> its own id
 *   tracking.adapter names another folder
 *   that has adapter.ts                    -> that id (chronopost -> la-poste)
 *   anything else                          -> not registered yet (served by the
 *                                             host's legacy dispatch until moved)
 *
 * `--check` fails when the committed registry is stale. `--strict` also fails
 * when an automatic carrier is not registered, which becomes the default once
 * every adapter lives in its folder.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const carriersRoot = path.join(packageRoot, 'carriers');
const outputPath = path.join(packageRoot, 'generated', 'registry.ts');
const recognitionPath = path.join(packageRoot, 'generated', 'recognition.ts');

function importName(id) {
  const words = id.split(/[^a-z0-9]+/i).filter(Boolean);
  return words.map((word, index) => (index === 0 ? word : word[0].toUpperCase() + word.slice(1))).join('');
}

const folders = readdirSync(carriersRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();
const definitions = new Map(folders.map((folder) => [
  folder, JSON.parse(readFileSync(path.join(carriersRoot, folder, 'carrier.json'), 'utf8')),
]));
const withAdapter = folders.filter((folder) => existsSync(path.join(carriersRoot, folder, 'adapter.ts')));

const carriers = {};
const unresolved = [];
for (const [id, definition] of definitions) {
  const tracking = definition.tracking ?? {};
  if (tracking.mode === 'link-only') { carriers[id] = null; continue; }
  if (tracking.adapter === 'universal') { carriers[id] = 'universal'; continue; }
  if (withAdapter.includes(id)) { carriers[id] = id; continue; }
  if (typeof tracking.adapter === 'string' && withAdapter.includes(tracking.adapter)) { carriers[id] = tracking.adapter; continue; }
  unresolved.push(id);
}

const lines = [
  '/* This file is generated by packages/carriers/scripts/generate-registry.mjs. Do not edit. */',
  '',
  "import type { RegistryDefinition } from '../core/adapter';",
  ...withAdapter.map((id) => `import { adapter as ${importName(id)} } from '../carriers/${id}/adapter';`),
  '',
  'export const REGISTRY: RegistryDefinition = {',
  '  factories: {',
  ...withAdapter.map((id) => `    ${JSON.stringify(id)}: ${importName(id)},`),
  '  },',
  '  carriers: {',
  ...Object.entries(carriers).map(([id, adapter]) => `    ${JSON.stringify(id)}: ${JSON.stringify(adapter)},`),
  '  },',
  '};',
  '',
  '/** Automatic carriers still served by the host until their adapter moves into its folder. */',
  `export const UNREGISTERED_CARRIERS: readonly string[] = ${JSON.stringify(unresolved)};`,
  '',
];
const generated = lines.join('\n');

// Ranks are unique: the iOS catalog has no carrier order, so a tie could sort
// differently there than on the server, which asks and names them in rank order.
const rankOwners = new Map();
const ranks = [...definitions].filter(([, definition]) => definition.tracking?.recognition)
  .map(([id, definition]) => {
    if (carriers[id] === null || carriers[id] === 'universal' || carriers[id] === undefined) {
      throw new Error(`${id} declares recognition but has no dedicated adapter`);
    }
    const { rank } = definition.tracking.recognition;
    if (rankOwners.has(rank)) throw new Error(`${id} and ${rankOwners.get(rank)} share recognition rank ${rank}; ranks must be unique`);
    rankOwners.set(rank, id);
    return `  ${JSON.stringify(id)}: ${rank},`;
  });
const generatedRecognition = [
  '/* This file is generated by packages/carriers/scripts/generate-registry.mjs. Do not edit. */',
  '',
  '/** Carriers whose adapter can recognize a number, by popularity rank (carrier.json tracking.recognition). */',
  'export const CARRIER_RECOGNITION_RANKS: Readonly<Record<string, number>> = {',
  ...ranks,
  '};',
  '',
].join('\n');

if (process.argv.includes('--strict') && unresolved.length) {
  throw new Error(`Automatic carriers without a registered adapter: ${unresolved.join(', ')}`);
}
if (process.argv.includes('--check')) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== generated) {
    throw new Error('packages/carriers/generated/registry.ts is stale. Run npm run contract:generate.');
  }
  const currentRecognition = existsSync(recognitionPath) ? readFileSync(recognitionPath, 'utf8') : '';
  if (currentRecognition !== generatedRecognition) {
    throw new Error('packages/carriers/generated/recognition.ts is stale. Run npm run contract:generate.');
  }
  console.log(`Carrier registry is current: ${withAdapter.length} adapters, ${unresolved.length} carriers still on legacy dispatch.`);
} else {
  writeFileSync(outputPath, generated);
  writeFileSync(recognitionPath, generatedRecognition);
  console.log(`Generated carrier registry: ${withAdapter.length} adapters, ${unresolved.length} carriers still on legacy dispatch.`);
}
